"""Read existing local desktop settings. No model catalog or write capability.

The returned settings describe the desktop's next-turn selection, not the model
used by a previous or currently running turn. This private protocol is gated by
codex_desktop_control's installed-build and local-socket checks.
"""
import time

import codex_desktop_control as _transport


class _ReadConnection(_transport._Connection):
    """Reuse bounded framing while refusing every non-read request on the wire."""

    def __init__(self, path, conversation_id):
        self._conversation_id = conversation_id
        super().__init__(path)

    def _send(self, message, mutation=False):
        kind = message.get('type')
        if kind == 'request':
            method, params = message.get('method'), message.get('params')
            allowed = {
                'initialize': (0, {'clientType': 'watch-model-settings-reader'}),
                'thread-owner-discovery': (1, {'hostId': 'local', 'conversationId': self._conversation_id}),
                'thread-follower-read-model-settings': (1, {'conversationId': self._conversation_id}),
            }
            _transport._require(method in allowed)
            version, expected = allowed[method]
            _transport._require(type(message.get('version')) is int
                                and message['version'] == version and params == expected)
        else:
            # Only protocol coordination responses generated by the base reader.
            _transport._require(kind in ('response', 'client-discovery-response'))
        super()._send(message, mutation=False)


def _text(value, maximum, nullable=False):
    if nullable and value is None:
        return None
    _transport._require(isinstance(value, str) and 0 < len(value) <= maximum
                        and value == value.strip()
                        and not any(ord(c) < 32 or ord(c) == 127 for c in value))
    return value


def _settings(value):
    _transport._require(isinstance(value, dict))
    # Do not silently normalize missing fields into null/default selections.
    _transport._require(all(k in value for k in ('model', 'reasoningEffort', 'mode', 'modelProvider')))
    mode = value['mode']
    _transport._require(mode is None or (isinstance(mode, str) and mode in ('default', 'plan')))
    return {'model': _text(value['model'], 256),
            'effort': _text(value['reasoningEffort'], 64, nullable=True),
            'mode': mode,
            'modelProvider': _text(value['modelProvider'], 128, nullable=True),
            'source': 'native_desktop_settings', 'observedAt': time.time()}


def read_settings(conversation_id, *, host_id='local'):
    """Read one exact existing owner. Never starts/resumes a chat or changes it.

    Callers must authorize the target independently. Names and log-derived model
    labels are not identities. No catalog means both selection capabilities stay
    false, including when a native settings read succeeds.
    """
    result = {'provider': 'codex', 'hostId': None, 'nativeThreadId': None,
              'state': 'unavailable', 'settings': None, 'catalog': None,
              'capability': {'read': False, 'selectModel': False, 'selectEffort': False,
                             'reason': 'invalid_target', 'scope': 'next_turn'}}
    connection = None
    try:
        _transport._id(conversation_id)
        result['nativeThreadId'] = conversation_id
        if host_id != 'local':
            result['capability']['reason'] = 'unsupported_host'
            return result
        result['hostId'] = 'local'
        result['capability']['reason'] = 'incompatible_desktop'
        _transport._verify_build()
        result['capability']['reason'] = 'transport_unavailable'
        connection = _ReadConnection(_transport._endpoint(), conversation_id)
        init = connection.request('initialize', {'clientType': 'watch-model-settings-reader'},
                                  'initializing-client', 0)
        client = _transport._id(init['result'].get('clientId'))
        _transport._require(init['handledByClientId'] == client)
        result['capability']['reason'] = 'owner_unavailable'
        found = connection.request('thread-owner-discovery',
                                   {'hostId': 'local', 'conversationId': conversation_id}, client, 1)
        owner = _transport._id(found['handledByClientId'])
        _transport._require(owner != client and found['result'].get('supportsUntrustedAppInput') is True)
        result['capability']['reason'] = 'native_read_unavailable'
        response = connection.request('thread-follower-read-model-settings',
                                      {'conversationId': conversation_id}, client, 1, owner)
        result['capability']['reason'] = 'invalid_native_settings'
        settings = _settings(response['result'].get('settings'))
        result.update(state='observed', settings=settings)
        result['capability'].update(read=True, reason='catalog_unavailable')
    except Exception:
        # No native error text, account/config data or local paths cross this boundary.
        pass
    finally:
        if connection is not None:
            connection.close()
    return result
